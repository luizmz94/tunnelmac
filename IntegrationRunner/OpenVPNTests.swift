// OpenVPN local checks. Synthetic profiles with fake PEM material shaped like the two
// formats validated by hand (single .ovpn with inline keys; Viscosity .visc folder with
// external files). No VPN, no network, no privileges; Keychain items use a disposable service.
@MainActor
enum OpenVPNTests {
    nonisolated static let fakeCertificate = "-----BEGIN CERTIFICATE-----\nMIIBfakeCERTIFICATEdataForLocalChecksOnly\n-----END CERTIFICATE-----"
    nonisolated static let fakeKey = "-----BEGIN PRIVATE KEY-----\nMIIEfakePRIVATEkeyForLocalChecksOnly\n-----END PRIVATE KEY-----"
    nonisolated static let fakeStatic = "#\n# 2048 bit OpenVPN static key\n#\n-----BEGIN OpenVPN Static key V1-----\n0123456789abcdef0123456789abcdef\n-----END OpenVPN Static key V1-----"

    /// Shape of the SUMMIT export: one file, inline material, two TCP remotes, RSA-SHA256, LZO.
    nonisolated static var singleFile: String {
        """
        dev tun
        persist-tun
        persist-key
        proto tcp-client
        cipher AES-256-CBC
        auth RSA-SHA256
        client
        resolv-retry infinite
        remote sslvpn1.example.invalid 2400 tcp
        remote sslvpn2.example.invalid 2400 tcp
        lport 0
        verify-x509-name "C=BR, ST=RS, L=Cidade, O=Exemplo, emailAddress=support@example.invalid, CN=sslvpn-certificate" subject
        remote-cert-tls server
        comp-lzo adaptive
        <ca>
        \(fakeCertificate)
        </ca>
        <cert>
        \(fakeCertificate)
        </cert>
        <key>
        \(fakeKey)
        </key>
        <tls-auth>
        \(fakeStatic)
        </tls-auth>
        key-direction 1
        """
    }

    /// Shape of the pfSense/Viscosity bundle: external files, tls-auth direction, user/password.
    nonisolated static let viscosity = """
    #-- Config Auto Generated By pfSense for Viscosity --#
    #viscosity startonopen false
    #viscosity name VPN_Clients
    dev tun
    persist-tun
    persist-key
    data-ciphers AES-256-GCM:AES-256-CBC
    data-ciphers-fallback AES-256-CBC
    auth SHA256
    tls-client
    client
    resolv-retry infinite
    remote 192.0.2.10 1194 udp4
    nobind
    verify-x509-name "EXEMPLO-VPN" name
    auth-user-pass
    remote-cert-tls server
    explicit-exit-notify
    ca ca.crt
    tls-auth ta.key 1
    cert cert.crt
    key key.key
    """

    static func run() -> Int {
        var failures = 0
        func test(_ name: String, _ block: () throws -> Void) {
            do { try block(); print("PASS: OpenVPN: \(name)") }
            catch { failures += 1; print("FAIL: OpenVPN: \(name): \(error.localizedDescription)") }
        }
        let require = TestSupport.require
        let spin = TestSupport.spin
        let root = FileManager.default.temporaryDirectory.appendingPathComponent("VPNGUI-openvpn-tests-\(UUID())")
        try? FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        let passwords = PasswordStore(service: "com.luiz.vpngui.tests.openvpn-password.\(UUID())")
        var created: [UUID] = []
        defer { for id in created { try? passwords.delete(id) } }

        func bundle(_ name: String = "Exemplo.visc", config: String = viscosity, keyMode: mode_t = 0o644) throws -> URL {
            let folder = root.appendingPathComponent(UUID().uuidString).appendingPathComponent(name)
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            try config.write(to: folder.appendingPathComponent("Summit.ovpn"), atomically: true, encoding: .utf8)
            try (fakeCertificate + "\n").write(to: folder.appendingPathComponent("ca.crt"), atomically: true, encoding: .utf8)
            try (fakeCertificate + "\n").write(to: folder.appendingPathComponent("cert.crt"), atomically: true, encoding: .utf8)
            try (fakeKey + "\n").write(to: folder.appendingPathComponent("key.key"), atomically: true, encoding: .utf8)
            try (fakeStatic + "\n").write(to: folder.appendingPathComponent("ta.key"), atomically: true, encoding: .utf8)
            chmod(folder.appendingPathComponent("key.key").path, keyMode)
            chmod(folder.appendingPathComponent("ta.key").path, keyMode)
            return folder
        }
        func digest(_ folder: URL) throws -> String {
            try FileManager.default.contentsOfDirectory(atPath: folder.path).sorted().map {
                TestSupport.sha256(try Data(contentsOf: folder.appendingPathComponent($0))) + $0
            }.joined()
        }
        func expectFailure(_ what: String, _ block: () throws -> Void) throws -> String {
            do { try block() } catch { return error.localizedDescription }
            throw TestSupport.Failure("\(what) foi aceito")
        }

        // MARK: Syntax and policy

        test("Sintaxe: aspas, escapes, comentários e metadados do Viscosity") {
            let parsed = try OpenVPNConfigText.parse("#viscosity name Escritório\nremote vpn.invalid 1194 # comentário\nverify-x509-name \"a \\\"b\\\" c\" name\n; nada\npull-filter ignore 'route 10.0.0.0'\n")
            try require(parsed.viscosity["name"] == "Escritório", "Nome do Viscosity não lido")
            try require(parsed.lines.map(\.directive) == [OpenVPNDirective("remote", ["vpn.invalid", "1194"]),
                                                          OpenVPNDirective("verify-x509-name", ["a \"b\" c", "name"]),
                                                          OpenVPNDirective("pull-filter", ["ignore", "route 10.0.0.0"])],
                        "Tokens: \(parsed.lines.map(\.directive))")
            _ = try expectFailure("Aspas abertas") { _ = try OpenVPNConfigText.parse("remote \"vpn.invalid\n") }
            _ = try expectFailure("Bloco sem fim") { _ = try OpenVPNConfigText.parse("<ca>\nx\n") }
            // The canonical text survives a round trip, quotes and backslashes included.
            let profile = OpenVPNProfile(directives: [OpenVPNDirective("client"), OpenVPNDirective("remote", ["vpn.invalid"]),
                                                      OpenVPNDirective("verify-x509-name", ["C=BR, CN=a\\\"b", "subject"])],
                                         blocks: [OpenVPNBlock(tag: "ca", content: fakeCertificate)])
            try require(try OpenVPNProfile.validated(profile.text) == profile, "Texto canônico não reproduz o perfil")
        }

        test("Formato 1: arquivo único com material inline, dois servidores TCP, RSA-SHA256 e LZO") {
            let imported = try OpenVPNImporter.importText(singleFile, baseDirectory: root, suggestedName: "SUMMIT_SSL_VPN", source: "~/Downloads/x.ovpn")
            try require(imported.profile.remotes.map(\.display) == ["sslvpn1.example.invalid:2400/tcp", "sslvpn2.example.invalid:2400/tcp"],
                        "Servidores: \(imported.profile.remotes)")
            try require(imported.profile.blocks.map(\.tag) == ["ca", "cert", "key", "tls-auth"], "Blocos: \(imported.profile.blocks.map(\.tag))")
            try require(!imported.profile.requiresCredentials, "Perfil sem auth-user-pass pediu credenciais")
            try require(imported.digestFix == OpenVPNCompatibility.DigestFix(from: "RSA-SHA256", to: "SHA256"), "RSA-SHA256 não detectado")
            try require(imported.warnings.contains { $0.contains("compressão") }, "Compressão sem aviso")
            // Without consent nothing changes; with consent only that value changes.
            try require(imported.profileText(applyingFix: false).contains("auth \"RSA-SHA256\""), "Correção aplicada sem consentimento")
            let fixed = imported.profileText(applyingFix: true)
            try require(fixed.contains("auth \"SHA256\"") && !fixed.contains("RSA-SHA256"), "Correção não aplicada")
            try require(try OpenVPNProfile.validated(fixed).directives.count == imported.profile.directives.count, "A correção mudou outras diretivas")
            try require(OpenVPNCompatibility.digestFix("SHA256") == nil && OpenVPNCompatibility.digestFix("RSA-MD5") == nil
                        && OpenVPNCompatibility.digestFix("xRSA-SHA256") == nil, "Mapeamento genérico demais")
            let logged = OpenVPNCompatibility.digestFix(fromLog: "2026-10-24 12:00:00 Message hash algorithm 'RSA-SHA256' not found")
            try require(logged?.to == "SHA256", "Erro do OpenVPN não reconhecido")
        }

        test("Formato 2: pasta .visc com arquivos externos, tls-auth com direção e usuário/senha; originais intactos") {
            let folder = try bundle()
            let before = try digest(folder)
            let imported = try OpenVPNImporter.load(folder)
            try require(try digest(folder) == before, "Arquivos originais foram alterados")
            try require(imported.name == "Summit", "Nome sugerido: \(imported.name)")
            try require(imported.sourceFolder?.path == folder.standardizedFileURL.path && imported.sourceFiles.count == 5,
                        "Limpeza da pasta .visc: \(String(describing: imported.sourceFolder)) \(imported.sourceFiles.count)")
            try require(imported.profile.requiresCredentials, "auth-user-pass não detectado")
            try require(Set(imported.profile.blocks.map(\.tag)) == ["ca", "cert", "key", "tls-auth"], "Arquivos não viraram inline")
            try require(imported.profile.directives.contains(OpenVPNDirective("key-direction", ["1"])), "Direção do tls-auth perdida")
            try require(!imported.profile.directives.contains { OpenVPNRules.blockTags.contains($0.name) }, "Referência a arquivo permaneceu")
            try require(imported.profile.remotes.map(\.display) == ["192.0.2.10:1194/udp"], "Servidor: \(imported.profile.remotes)")
            try require(imported.digestFix == nil, "auth SHA256 marcado como incompatível")
            try require(imported.warnings.contains { $0.contains("key.key") && $0.contains("chmod 600") }
                        && imported.warnings.contains { $0.contains("ta.key") }, "Chaves legíveis por outros sem aviso")
            try require(!imported.warnings.contains { $0.contains("ca.crt") }, "Certificado público tratado como segredo")
            // The detail only warns while an exposed original is still there and still exposed.
            try require(Set(imported.summary.stillExposed.map { ($0 as NSString).lastPathComponent }) == ["key.key", "ta.key"], "Originais expostos")
            chmod(folder.appendingPathComponent("key.key").path, 0o600)
            try FileManager.default.removeItem(at: folder.appendingPathComponent("ta.key"))
            try require(imported.summary.stillExposed.isEmpty, "Aviso continua depois de corrigir/apagar os originais")
            try (fakeStatic + "\n").write(to: folder.appendingPathComponent("ta.key"), atomically: true, encoding: .utf8)
            let privateFolder = try OpenVPNImporter.load(try bundle(keyMode: 0o600))
            try require(!privateFolder.warnings.contains { $0.contains("chmod") }, "Aviso de permissão indevido")
            // The file itself can be chosen too; a folder with two profiles asks for a choice.
            _ = try OpenVPNImporter.load(folder.appendingPathComponent("Summit.ovpn"))
            try viscosity.write(to: folder.appendingPathComponent("Outro.ovpn"), atomically: true, encoding: .utf8)
            let message = try expectFailure("Pasta ambígua") { _ = try OpenVPNImporter.load(folder) }
            try require(message.contains("mais de um perfil"), message)
        }

        test("Vários arquivos escolhidos juntos: perfil + certificados de outra pasta, nomes repetidos e sobras") {
            let profileFolder = root.appendingPathComponent("perfil-\(UUID())")
            let certFolder = root.appendingPathComponent("certs-\(UUID())")
            try FileManager.default.createDirectory(at: profileFolder, withIntermediateDirectories: true)
            try FileManager.default.createDirectory(at: certFolder, withIntermediateDirectories: true)
            let config = profileFolder.appendingPathComponent("Summit.ovpn")
            try viscosity.write(to: config, atomically: true, encoding: .utf8)
            var files: [URL] = []
            for (name, content) in [("ca.crt", fakeCertificate), ("cert.crt", fakeCertificate), ("key.key", fakeKey), ("ta.key", fakeStatic), ("extra.txt", "x")] {
                let url = certFolder.appendingPathComponent(name)
                try (content + "\n").write(to: url, atomically: true, encoding: .utf8)
                chmod(url.path, 0o600)
                files.append(url)
            }
            _ = try expectFailure("Certificados em outra pasta sem seleção") { _ = try OpenVPNImporter.load(config) }
            let imported = try OpenVPNImporter.load([config] + files)
            try require(Set(imported.profile.blocks.map(\.tag)) == ["ca", "cert", "key", "tls-auth"], "Anexos não usados")
            try require(imported.warnings.contains { $0.contains("extra.txt") }, "Arquivo sobrando sem aviso")
            try require(imported.sourceFolder == nil && Set(imported.sourceFiles.map(\.lastPathComponent)) == ["Summit.ovpn", "ca.crt", "cert.crt", "key.key", "ta.key"],
                        "Originais oferecidos para a Lixeira: \(imported.sourceFiles.map(\.lastPathComponent))")
            _ = try expectFailure("Dois perfis") { _ = try OpenVPNImporter.load([config, config.deletingLastPathComponent().appendingPathComponent("x.conf")] + files) }
            _ = try expectFailure("Sem perfil") { _ = try OpenVPNImporter.load(files) }
            _ = try expectFailure("Pasta na seleção múltipla") { _ = try OpenVPNImporter.load([config, certFolder]) }
        }

        test("Compatibilidade reversível: aplicar, detectar e voltar ao valor original") {
            let imported = try OpenVPNImporter.importText(singleFile, baseDirectory: root, suggestedName: "x", source: "")
            guard let fix = imported.summary.compatibility else { throw TestSupport.Failure("Resumo sem a opção de compatibilidade") }
            let fixed = OpenVPNCompatibility.apply(fix, to: imported.profile)
            try require(OpenVPNCompatibility.isApplied(fix, in: fixed) && !OpenVPNCompatibility.isApplied(fix, in: imported.profile), "Estado")
            try require(OpenVPNCompatibility.revert(fix, in: fixed) == imported.profile, "Desligar não voltou ao original")
            let summary = try JSONDecoder().decode(OpenVPNSummary.self, from: JSONEncoder().encode(imported.summary))
            try require(summary.compatibility == fix, "Opção não persiste no cadastro")
        }

        test("Referências: fora da pasta, absolutas, com .. ou por link simbólico são recusadas") {
            for reference in ["../ca.crt", "/etc/hosts", "~/ca.crt", "sub/../../ca.crt"] {
