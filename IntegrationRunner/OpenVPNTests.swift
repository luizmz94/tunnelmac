        test("Conectar: pedido OpenVPN com perfil e credenciais; túnel, AUTH_FAILED e RSA-SHA256 com correção confirmada") {
            let model = AppModel(store: try JSONStore(directory: root.appendingPathComponent("connect-\(UUID())")), passwords: passwords,
                                 service: HelperTests.readyService())
            var requests: [OpenVPNRequest] = []
            model.manager.harness = VPNManager.LaunchHarness(help: SAMLCookieTests.help, launched: { _, _, _ in
                requests.append(OpenVPNRequest(connectionID: UUID(), profile: "fortinet", username: nil, password: nil))
            }, openVPNLaunched: { session, request in
                requests.append(request)
                session.state = .connecting
            })
            let imported = try OpenVPNImporter.importText(singleFile, baseDirectory: root, suggestedName: "Inline", source: "")
            let connection = Connection(name: "Inline", kind: .openvpn, openVPN: imported.summary)
            created.append(connection.id)
            try model.save(connection, password: "", openVPNProfile: imported.profileText(applyingFix: false))
            model.connect(connection)
            try require(requests.count == 1 && requests[0].profile == imported.profile.text && requests[0].username == nil && requests[0].password == nil,
                        "Pedido: \(requests.map(\.connectionID))")
            let session = model.manager.session(connection.id)
            try require(session.logs.contains { $0.contains("OpenVPN") }, "Log inicial não menciona o OpenVPN")
            session.accept("2026-10-24 12:00:00 Message hash algorithm 'RSA-SHA256' not found", connection: connection) { _ in }
            try require(session.digestFix?.to == "SHA256" && session.retryBlocked, "Erro de digest não oferece correção")
            model.manager.end(session, exit: 1)
            try require(try model.profiles?.read(connection.id).contains("RSA-SHA256") == true, "Perfil alterado sem confirmação")
            try model.applyDigestFix(connection, OpenVPNCompatibility.DigestFix(from: "RSA-SHA256", to: "SHA256"))
            try require(try model.profiles?.read(connection.id).contains("auth \"SHA256\"") == true, "Correção não gravada")
            try require(requests.count == 2 && requests[1].profile.contains("auth \"SHA256\""), "Não reconectou com o perfil corrigido")
            session.accept("2026-10-24 12:00:05 Initialization Sequence Completed", connection: connection) { _ in }
            try require(session.state == .connected && session.connectedAt != nil && session.retryDelay == 10, "Túnel não marcado como conectado")
            session.accept("2026-10-24 12:10:00 SIGUSR1[soft,ping-restart] received, process restarting", connection: connection) { _ in }
            try require(session.state == .connecting && session.connectedAt == nil, "Reinício interno do OpenVPN não refletido")
            session.accept("2026-10-24 12:10:00 AUTH: Received control message: AUTH_FAILED", connection: connection) { _ in }
            try require(session.authenticationRejected && session.retryBlocked, "AUTH_FAILED não bloqueou novas tentativas")
