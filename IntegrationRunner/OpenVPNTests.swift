                try require(message.contains("fora da pasta"), "\(reference): \(message)")
            }
            let folder = try bundle()
            let outside = root.appendingPathComponent("segredo-\(UUID()).pem")
            try (fakeCertificate + "\n").write(to: outside, atomically: true, encoding: .utf8)
            try FileManager.default.removeItem(at: folder.appendingPathComponent("ca.crt"))
            try FileManager.default.createSymbolicLink(at: folder.appendingPathComponent("ca.crt"), withDestinationURL: outside)
            let message = try expectFailure("Link simbólico") { _ = try OpenVPNImporter.load(folder) }
            try require(message.contains("fora da pasta"), message)
        }

